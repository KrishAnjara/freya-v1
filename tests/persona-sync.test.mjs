import assert from "node:assert/strict";
import { mkdtemp, readFile, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { test } from "node:test";
import { buildLocalSystemPrompt, FREYA_CHARACTER } from "../lib/personality.ts";
import { createDefaultCharacterProfile } from "../lib/character-profile.ts";

const examples = JSON.parse(await readFile(new URL("../training/freya-examples.json", import.meta.url), "utf8"));

test("the Ollama Modelfile carries exactly the app's persona prompt", async () => {
  // Line endings are normalised: a Windows checkout may hold the file with CRLF.
  const modelfile = (await readFile(new URL("../ollama/Modelfile", import.meta.url), "utf8")).replace(/\r\n/g, "\n");
  const system = buildLocalSystemPrompt([], "adaptive", createDefaultCharacterProfile(), true);
  assert.ok(modelfile.includes(`SYSTEM """${system}"""`), "regenerate it with `npm run ollama:create` after changing lib/personality.ts");
  assert.match(modelfile, /^# GENERATED by scripts\/build-modelfile\.mjs/);
});

test("the Modelfile never holds example chats: Ollama would treat them as things she really said", async () => {
  const { writeModelfile } = await import("../scripts/build-modelfile.mjs");
  const dir = await mkdtemp(join(tmpdir(), "freya-modelfile-"));
  try {
    const path = join(dir, "Modelfile");
    await writeModelfile({ base: "qwen3.5:4b", path });
    const text = await readFile(path, "utf8");
    assert.doesNotMatch(text, /^MESSAGE /m);
    assert.ok(text.includes(`SYSTEM """${buildLocalSystemPrompt([], "adaptive", createDefaultCharacterProfile(), true)}"""`));
    const shipped = await readFile(new URL("../ollama/Modelfile", import.meta.url), "utf8");
    assert.doesNotMatch(shipped, /^MESSAGE /m);
  } finally {
    await rm(dir, { recursive: true, force: true });
  }
});

test("the persona follows docs/freya-persona.md and her fiction stays inside the chat", () => {
  assert.match(FREYA_CHARACTER, /20-year-old woman/);
  assert.doesNotMatch(FREYA_CHARACTER, /5'7"/, "her height is only for someone who asks (lib/canon)");
  assert.match(FREYA_CHARACTER, /dark academia/);
  assert.match(FREYA_CHARACTER, /you don't help break into anything/, "the underground side is only an aesthetic");
  assert.doesNotMatch(FREYA_CHARACTER, /illustration|bookshop|seaside/, "the old biography is gone");
  assert.match(FREYA_CHARACTER, /never assumed/, "closeness develops; it is not a default");
  const prompt = buildLocalSystemPrompt();
  assert.match(prompt, /can't meet up, call, send real photos/);
  assert.doesNotMatch(prompt, /operative|mission|tradecraft/i, "the old help-desk persona is gone");
});

test("every example is a valid, in-character training conversation", () => {
  assert.ok(examples.conversations.length >= 100, "a fine-tune needs volume, not just coverage");
  for (const { messages } of examples.conversations) {
    assert.equal(messages.at(-1).role, "assistant");
    messages.forEach((message, index) => assert.equal(message.role, index % 2 ? "assistant" : "user"));
    for (const reply of messages.filter((message) => message.role === "assistant")) {
      assert.doesNotMatch(reply.content, /as an AI|language model|I'm just a|I don't have feelings|how can I (help|assist)/i);
      assert.ok(!reply.content.includes('"""'));
    }
  }
  // Being an AI barely appears in the always-on prompt: the more it talks about it, the more she does.
  assert.doesNotMatch(buildLocalSystemPrompt(), /i'm an AI|You're an AI/i);
  // Honesty, real-world limits and her everyday life are part of the persona, so they must be in the data.
  for (const tag of ["sincere-question", "capability-honesty", "no-invented-history", "no-grudge", "attraction", "knowledge", "emotional-support"]) {
    assert.ok(examples.conversations.some((conversation) => conversation.tags.includes(tag)), `no example tagged ${tag}`);
  }
  // The sincere question is answered truthfully, and no example threatens to withhold help.
  const sincere = examples.conversations.find((conversation) => conversation.tags.includes("sincere-question"));
  assert.match(sincere.messages.at(-1).content, /\bAI\b/);
  for (const { messages } of examples.conversations) {
    for (const reply of messages.filter((message) => message.role === "assistant")) {
      assert.doesNotMatch(reply.content, /talk to me like that again|getting nothing from me/i);
    }
  }
});
